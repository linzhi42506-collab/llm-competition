#!/usr/bin/env bash
# ============================================================================
#  打包比赛提交材料（省赛/区域赛需要：视频 + 技术文档 + 算法源码）
#  产物放在 10_提交材料/ 下
# ============================================================================
set -e
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "${HERE}")"
OUT="${ROOT}/10_提交材料"
STAMP="$(date +%Y%m%d)"

mkdir -p "${OUT}"

echo ">>> 1/3 打包算法源码 ..."
SRC_PKG="${OUT}/算法源码_${STAMP}.tar.gz"
tar -czf "${SRC_PKG}" \
    --exclude='*/__pycache__' \
    --exclude='*/build' --exclude='*/install' --exclude='*/log' \
    -C "${ROOT}/01_dev_ws/dev_ws" \
    src/llm_comp src/yzbot \
    -C "${ROOT}" \
    06_脚本 05_文档
echo "    ${SRC_PKG}  ($(du -h "${SRC_PKG}" | cut -f1))"

echo ">>> 2/3 复制技术文档草稿 ..."
cp "${ROOT}/05_文档/04_技术文档（提交用草稿）.md" "${OUT}/技术文档_${STAMP}.md"
echo "    注意：提交前请转成 Word，并填写首页的参赛编号/团队名称/团队成员"

echo ">>> 3/3 检查视频是否就位 ..."
if ls "${ROOT}/video"/*.mp4 >/dev/null 2>&1; then
    echo "    找到视频，复制到 ${OUT}"
    cp "${ROOT}/video"/*.mp4 "${OUT}/"
else
    echo "    ⚠ 未找到视频：请把双机位录制的视频放到 ${ROOT}/video/ 后重新运行本脚本"
fi

cat <<EOF

============================================================
 提交材料已生成: ${OUT}
------------------------------------------------------------
 请核对（官方要求）:
   ① 视频：电脑 + 手机双机位，一镜到底，
      不允许加速/删减/拼接/特效，必须展示官方比赛系统 U 盘及编号；
   ② 技术文档：Word，首页注明 赛道名称(算法应用赛) /
      赛题名称(大模型技术创新赛) / 参赛编号 / 团队名称 / 团队成员；
   ③ 算法源码：压缩包（本脚本已生成）。
   三项统一上传百度网盘。
============================================================
EOF
